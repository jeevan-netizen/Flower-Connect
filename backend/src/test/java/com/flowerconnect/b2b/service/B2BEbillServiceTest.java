package com.flowerconnect.b2b.service;

import com.flowerconnect.b2b.domain.B2BOrder;
import com.flowerconnect.b2b.domain.B2BOrder.PaymentStatus;
import com.flowerconnect.b2b.domain.B2BOrderItem;
import com.flowerconnect.b2b.repository.B2BOrderItemRepository;
import com.flowerconnect.b2b.repository.B2BOrderRepository;
import com.flowerconnect.domain.VendorProfile;
import com.flowerconnect.exception.BusinessException;
import com.flowerconnect.exception.ErrorCode;
import com.flowerconnect.repository.VendorProfileRepository;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.mockito.junit.jupiter.MockitoSettings;
import org.mockito.quality.Strictness;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * Unit tests for {@link B2BEbillService}.
 *
 * <p>Covers e-bill download authorisation (buyer/seller yes, third vendor no),
 * refusal for every non-{@code DELIVERED} status, bill-number stability across
 * repeated downloads, and that the generated bytes are a valid PDF containing
 * the expected order/bill identifiers and snapshot content.
 *
 * <p>HTTP wiring, RBAC and the bill-number assignment on delivery are covered
 * by {@code B2BOrderIntegrationTest} and {@code B2BOrderControllerTest}.
 */
@ExtendWith(MockitoExtension.class)
@MockitoSettings(strictness = Strictness.LENIENT)
class B2BEbillServiceTest {

    private static final String BUYER_EMAIL = "buyer@test.com";
    private static final String SELLER_EMAIL = "seller@test.com";
    private static final String THIRD_EMAIL = "third@test.com";
    private static final Long BUYER_ID = 1L;
    private static final Long SELLER_ID = 2L;
    private static final Long THIRD_ID = 3L;
    private static final Long ORDER_ID = 10L;

    private static final Clock CLOCK = Clock.fixed(Instant.parse("2026-11-25T10:00:00Z"), ZoneOffset.UTC);

    @Mock
    private B2BOrderRepository orderRepository;
    @Mock
    private B2BOrderItemRepository orderItemRepository;
    @Mock
    private VendorProfileRepository vendorProfileRepository;

    private B2BEbillService service;

    @BeforeEach
    void setUp() {
        service = new B2BEbillService(
                orderRepository, orderItemRepository, vendorProfileRepository, CLOCK);
    }

    // ------------------------------------------------------------------
    // Fixtures
    // ------------------------------------------------------------------

    private VendorProfile vendor(Long id, String email, String businessName,
                                 VendorProfile.Status status) {
        VendorProfile v = VendorProfile.builder()
                .id(id)
                .businessName(businessName)
                .status(status)
                .build();
        when(vendorProfileRepository.findByUserEmail(email)).thenReturn(Optional.of(v));
        return v;
    }

    private B2BOrder deliveredOrder() {
        VendorProfile buyer = VendorProfile.builder().id(BUYER_ID).businessName("Buyer Florist").build();
        VendorProfile seller = VendorProfile.builder().id(SELLER_ID).businessName("Seller Florist").build();
        B2BOrderItem item = B2BOrderItem.builder()
                .productName("Red Roses")
                .unit("kg")
                .quantity(3)
                .unitPrice(new BigDecimal("199.00"))
                .lineTotal(new BigDecimal("597.00"))
                .build();
        B2BOrder order = B2BOrder.builder()
                .id(ORDER_ID)
                .orderNo("B2B-10")
                .buyer(buyer)
                .seller(seller)
                .status(B2BOrder.Status.DELIVERED)
                .paymentStatus(PaymentStatus.UNPAID)
                .total(new BigDecimal("597.00"))
                .orderNote("Please wrap nicely")
                .shipmentReference("TRACK-123")
                .billNumber("EB-2026-000010")
                .deliveredAt(LocalDateTime.now(CLOCK))
                .build();
        order.addItem(item);
        when(orderRepository.findById(ORDER_ID)).thenReturn(Optional.of(order));
        when(orderItemRepository.findByOrderId(ORDER_ID)).thenReturn(List.of(item));
        return order;
    }

    private B2BOrder orderWithStatus(B2BOrder.Status status) {
        VendorProfile buyer = VendorProfile.builder().id(BUYER_ID).businessName("Buyer Florist").build();
        VendorProfile seller = VendorProfile.builder().id(SELLER_ID).businessName("Seller Florist").build();
        B2BOrder order = B2BOrder.builder()
                .id(ORDER_ID)
                .orderNo("B2B-10")
                .buyer(buyer)
                .seller(seller)
                .status(status)
                .paymentStatus(PaymentStatus.UNPAID)
                .total(new BigDecimal("597.00"))
                .build();
        when(orderRepository.findById(ORDER_ID)).thenReturn(Optional.of(order));
        return order;
    }

    // ------------------------------------------------------------------
    // Download: buyer and seller
    // ------------------------------------------------------------------

    @Test
    void buyerCanDownloadEbill() {
        vendor(BUYER_ID, BUYER_EMAIL, "Buyer Florist", VendorProfile.Status.APPROVED);
        vendor(SELLER_ID, SELLER_EMAIL, "Seller Florist", VendorProfile.Status.APPROVED);
        deliveredOrder();

        byte[] pdf = service.generateEbillPdf(BUYER_EMAIL, ORDER_ID);

        assertThat(pdf).isNotNull();
        assertThat(isValidPdf(pdf)).isTrue();
        assertThat(pdfText(pdf))
                .contains("EB-2026-000010")
                .contains("B2B-10")
                .contains("Buyer Florist")
                .contains("Seller Florist")
                .contains("Red Roses")
                .contains("199.00")
                .contains("597.00")
                .contains("TRACK-123");
    }

    @Test
    void sellerCanDownloadEbill() {
        vendor(BUYER_ID, BUYER_EMAIL, "Buyer Florist", VendorProfile.Status.APPROVED);
        vendor(SELLER_ID, SELLER_EMAIL, "Seller Florist", VendorProfile.Status.APPROVED);
        deliveredOrder();

        byte[] pdf = service.generateEbillPdf(SELLER_EMAIL, ORDER_ID);

        assertThat(pdf).isNotNull();
        assertThat(isValidPdf(pdf)).isTrue();
        assertThat(pdfText(pdf)).contains("EB-2026-000010");
    }

    // ------------------------------------------------------------------
    // Download: third vendor forbidden
    // ------------------------------------------------------------------

    @Test
    void thirdVendorCannotDownloadEbill() {
        vendor(BUYER_ID, BUYER_EMAIL, "Buyer Florist", VendorProfile.Status.APPROVED);
        vendor(SELLER_ID, SELLER_EMAIL, "Seller Florist", VendorProfile.Status.APPROVED);
        vendor(THIRD_ID, THIRD_EMAIL, "Third Florist", VendorProfile.Status.APPROVED);
        deliveredOrder();

        assertThatThrownBy(() -> service.generateEbillPdf(THIRD_EMAIL, ORDER_ID))
                .isInstanceOf(BusinessException.class)
                .extracting("errorCode")
                .isEqualTo(ErrorCode.FORBIDDEN);
    }

    // ------------------------------------------------------------------
    // Download refused for every non-DELIVERED status
    // ------------------------------------------------------------------

    @Test
    void ebillRefusedForEveryNonDeliveredStatus() {
        vendor(BUYER_ID, BUYER_EMAIL, "Buyer Florist", VendorProfile.Status.APPROVED);
        vendor(SELLER_ID, SELLER_EMAIL, "Seller Florist", VendorProfile.Status.APPROVED);

        for (B2BOrder.Status status : new B2BOrder.Status[]{B2BOrder.Status.PLACED,
                B2BOrder.Status.ACCEPTED, B2BOrder.Status.SHIPPED,
                B2BOrder.Status.CANCELLED, B2BOrder.Status.REJECTED}) {
            orderWithStatus(status);

            assertThatThrownBy(() -> service.generateEbillPdf(BUYER_EMAIL, ORDER_ID))
                    .isInstanceOf(BusinessException.class)
                    .extracting("errorCode")
                    .isEqualTo(ErrorCode.E_BILL_NOT_AVAILABLE);
        }
    }

    // ------------------------------------------------------------------
    // Bill number stability
    // ------------------------------------------------------------------

    @Test
    void billNumberStableAcrossRepeatedDownloads() {
        vendor(BUYER_ID, BUYER_EMAIL, "Buyer Florist", VendorProfile.Status.APPROVED);
        vendor(SELLER_ID, SELLER_EMAIL, "Seller Florist", VendorProfile.Status.APPROVED);
        deliveredOrder();

        byte[] first = service.generateEbillPdf(BUYER_EMAIL, ORDER_ID);
        byte[] second = service.generateEbillPdf(BUYER_EMAIL, ORDER_ID);

        assertThat(pdfText(first)).isEqualTo(pdfText(second));
        assertThat(pdfText(first)).contains("EB-2026-000010");
    }

    // ------------------------------------------------------------------
    // Helpers
    // ------------------------------------------------------------------

    private boolean isValidPdf(byte[] bytes) {
        try (PDDocument document = PDDocument.load(bytes)) {
            return document.getNumberOfPages() > 0;
        } catch (Exception ex) {
            return false;
        }
    }

    private String pdfText(byte[] bytes) {
        try (PDDocument document = PDDocument.load(bytes)) {
            return new PDFTextStripper().getText(document);
        } catch (Exception ex) {
            throw new RuntimeException(ex);
        }
    }
}
